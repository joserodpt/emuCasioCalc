#!/usr/bin/env python3
"""Writes src/engine/os/font_data.c: the fonts the OS text syscalls draw with.

    tools/gen_fonts.py SPLEEN_DIR UNIFONT_HEX OUT.c

SPLEEN_DIR holds spleen-5x8.bdf, spleen-8x16.bdf and spleen-12x24.bdf
(Spleen 2.1.0, https://github.com/fcambus/spleen, BSD 2-clause); UNIFONT_HEX
is GNU Unifont 15.1.05's .hex file (SIL OFL 1.1), from which a subset of
symbols (Greek, arrows, maths...) is taken for characters Spleen lacks.
Licences: assets/fonts/.

Each glyph is stored at the font's full cell size, rows of (w + 7) / 8
bytes, most significant bit first, with its leftmost lit column and its
proportional advance (lit width + 1 px; half the cell for blank glyphs).
"""
import sys

# Unifont ranges kept: symbols that Casio text uses or that show up in
# add-ins' strings. CJK is left out (too big to embed).
UNIFONT_RANGES = [
    (0x00A0, 0x024F), (0x0370, 0x03FF), (0x0400, 0x04FF), (0x1D00, 0x1DBF),
    (0x2000, 0x23FF), (0x2460, 0x24FF), (0x2500, 0x27BF), (0x2900, 0x2BFF),
    (0xFFFD, 0xFFFD),
]


def proportional(rows, w):
    lit = [x for x in range(w) if any(r >> (w - 1 - x) & 1 for r in rows)]
    if not lit:
        return 0, max(2, w // 2)
    return lit[0], lit[-1] - lit[0] + 2


def read_bdf(path):
    glyphs, ascent = {}, 0
    W = H = 0
    with open(path, encoding="latin-1") as f:
        lines = iter(f.read().splitlines())
    for line in lines:
        k = line.split()
        if not k:
            continue
        if k[0] == "FONTBOUNDINGBOX":
            W, H = int(k[1]), int(k[2])
        elif k[0] == "FONT_ASCENT":
            ascent = int(k[1])
        elif k[0] == "STARTCHAR":
            enc, bbx, bitmap = -1, None, []
            for line in lines:
                k = line.split()
                if k[0] == "ENCODING":
                    enc = int(k[1])
                elif k[0] == "BBX":
                    bbx = [int(v) for v in k[1:5]]
                elif k[0] == "BITMAP":
                    for line in lines:
                        if line.strip() == "ENDCHAR":
                            break
                        bitmap.append(int(line.strip(), 16))
                    break
            if enc < 0 or bbx is None:
                continue
            bw, bh, bx, by = bbx
            row_bits = ((bw + 7) // 8) * 8
            rows = [0] * H
            top = ascent - (bh + by)
            for i, v in enumerate(bitmap):
                y = top + i
                if 0 <= y < H:
                    v >>= row_bits - bw  # drop padding bits
                    rows[y] |= (v << (W - bw - bx)) & ((1 << W) - 1)
            glyphs[enc] = (W, rows)
    return W, H, glyphs


def read_unifont(path):
    glyphs = {}
    with open(path) as f:
        for line in f:
            cp_s, hexbits = line.strip().split(":")
            cp = int(cp_s, 16)
            if not any(a <= cp <= b for a, b in UNIFONT_RANGES):
                continue
            w = 8 if len(hexbits) == 32 else 16
            step = w // 4
            rows = [int(hexbits[i:i + step], 16) for i in range(0, len(hexbits), step)]
            glyphs[cp] = (w, rows)
    return 16, glyphs


def emit(out, name, h, glyphs):
    table, bits = [], bytearray()
    for cp in sorted(glyphs):
        w, rows = glyphs[cp]
        left, adv = proportional(rows, w)
        table.append((cp, len(bits), w, left, adv))
        nb = (w + 7) // 8
        for r in rows:
            bits += (r << (nb * 8 - w)).to_bytes(nb, "big")
    out.append(f"static const uint8_t {name}_BITS[] =")
    for i in range(0, len(bits), 32):
        out.append('    "' + "".join(f"\\x{b:02X}" for b in bits[i:i + 32]) + '"')
    out.append(";")
    out.append(f"static const FontGlyph {name}_GLYPHS[] = {{")
    for i in range(0, len(table), 4):
        out.append("    " + " ".join("{0x%04X, %d, %d, %d, %d}," % t for t in table[i:i + 4]))
    out.append("};")
    out.append(f"const Font {name} = {{{h}, {len(table)}, {name}_GLYPHS, {name}_BITS}};")
    out.append("")


def main():
    spleen_dir, unifont, dest = sys.argv[1:4]
    out = ["/* Generated by tools/gen_fonts.py from Spleen 2.1.0 (BSD 2-clause) and",
           " * GNU Unifont 15.1.05 (SIL OFL 1.1): see assets/fonts/. Do not edit. */",
           "#include \"font.h\"", ""]
    for name, size in (("FONT_BIG", "12x24"), ("FONT_MINI", "8x16"), ("FONT_TINY", "5x8")):
        w, h, g = read_bdf(f"{spleen_dir}/spleen-{size}.bdf")
        emit(out, name, h, g)
    h, g = read_unifont(unifont)
    emit(out, "FONT_EXTRA", h, g)
    with open(dest, "w") as f:
        f.write("\n".join(out))


main()
